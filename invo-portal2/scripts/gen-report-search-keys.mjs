#!/usr/bin/env node
/**
 * Regenerates src/app/features/reports/models/report-body-search-keys.ts — run with `node scripts/gen-report-search-keys.mjs`
 * after adding or changing a report with its own body (`customBody`).
 *
 * Each such body is its own component, so its headings and column names are not in the catalog. This reads the body's
 * template/code, keeps the `REPORTS.*` translation keys that resolve to a short label, and writes them per `customBody`, so the
 * catalog search can look inside the report ("Sales By Category" finds Sales Summary). Flat and comparison reports are indexed
 * live from their own configs and need nothing here.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';

const root = 'src/app/features/reports';
const walk = d => readdirSync(d).flatMap(n => { const p = join(d, n); return statSync(p).isDirectory() ? walk(p) : [p]; });
const files = walk(root);

// customBody -> component selector, from the report view's template
const view = readFileSync(join(root, 'pages/report-view/report-view.component.html'), 'utf8');
const bodies = {};
for (const m of view.matchAll(/customBody === '([a-z-]+)'\)\s*\{\s*(?:<!--[\s\S]*?-->\s*)?<(app-[a-z-]+)/g)) bodies[m[1]] = m[2];

// selector -> component folder
const folderOf = {};
for (const f of files.filter(f => f.endsWith('.component.ts'))) {
  const m = readFileSync(f, 'utf8').match(/selector:\s*'(app-[a-z-]+)'/);
  if (m) folderOf[m[1]] = dirname(f);
}

const en = JSON.parse(readFileSync(join(root, 'i18n/en.json'), 'utf8'));
const resolve = key => key.split('.').reduce((o, k) => (o && typeof o === 'object' ? o[k] : undefined), en);
const SKIP = /(ERROR|EMPTY|LOADING|RETRY|HINT|NOTE|NONE|^NO_|\.NO_|EXPORT|PRINT|ACTION|SCHEDULE|FILTER\.|TOOLTIP|CONFIRM|TOAST|MSG)/;

const out = {};
for (const [body, sel] of Object.entries(bodies)) {
  const dir = folderOf[sel];
  if (!dir || body === 'flat' || body === 'comparison') continue;
  const keys = new Set();
  for (const f of files.filter(f => f.startsWith(dir) && /\.(html|ts)$/.test(f) && !f.endsWith('.spec.ts'))) {
    for (const m of readFileSync(f, 'utf8').matchAll(/'(REPORTS\.[A-Z0-9_.]+)'/g)) {
      const v = resolve(m[1]);
      if (typeof v === 'string' && v.length <= 60 && !SKIP.test(m[1])) keys.add(m[1]);
    }
  }
  if (keys.size) out[body] = [...keys].sort();
}

const lines = Object.entries(out).map(([b, k]) => `  '${b}': [\n${k.map(x => `    '${x}',`).join('\n')}\n  ],`);
writeFileSync(join(root, 'models/report-body-search-keys.ts'),
`/* GENERATED by scripts/gen-report-search-keys.mjs — do not edit. i18n keys of what each custom report body shows (headings, columns), for the catalog search. */
export const REPORT_BODY_SEARCH_KEYS: Record<string, string[]> = {
${lines.join('\n')}
};
`);
console.log(Object.entries(out).map(([b, k]) => `${b}: ${k.length}`).join('\n'));
