#!/usr/bin/env node
// Reads .env, then .env.local (wins over .env), then real process env vars
// (win over both, handy for CI) and writes the recognised keys into
// src/environments/environment.generated.ts — a gitignored file that
// environment.ts imports. environment.ts itself is never rewritten, so
// personal values (a LAN IP) can't be committed by accident.
//
// invo-portal2 is a plain client-side Angular app: the browser bundle can't
// read a .env file, so this is the build-time substitute. It runs from the
// `postinstall`, `prestart`, `prebuild`, `pretest` and `prewatch` npm
// scripts. Re-run `npm start` after editing .env — an already-running dev
// server won't see the change.
//
// Recognised keys (anything else is ignored with a warning):
//   {DEV,PROD}_BACKEND_URL / _SOCKET_URL / _DASHBOARD_URL / _WEBSITE_URL
// Unset keys fall back to the defaults hard-coded in environment.ts.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(fileURLToPath(import.meta.url), '../..');
const outPath = path.join(root, 'src/environments/environment.generated.ts');

const SERVICES = ['BACKEND_URL', 'SOCKET_URL', 'DASHBOARD_URL', 'WEBSITE_URL'];
const KEYS = ['DEV', 'PROD'].flatMap(tier => SERVICES.map(s => `${tier}_${s}`));

function parseEnvFile(filePath) {
  const out = {};
  if (!existsSync(filePath)) return out;
  for (const line of readFileSync(filePath, 'utf8').split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    let value = trimmed.slice(eq + 1).trim();
    if (/^(['"]).*\1$/.test(value)) value = value.slice(1, -1);
    out[trimmed.slice(0, eq).trim()] = value;
  }
  return out;
}

const fromFiles = {
  ...parseEnvFile(path.join(root, '.env')),
  ...parseEnvFile(path.join(root, '.env.local')),
};

for (const key of Object.keys(fromFiles)) {
  if (!KEYS.includes(key)) console.warn(`[apply-env] ignoring unknown key ${key}`);
}

const overrides = {};
for (const key of KEYS) {
  const value = process.env[key] ?? fromFiles[key];
  if (value !== undefined) overrides[key] = value;
}

const body = KEYS.map(k => (k in overrides ? `  ${k}: ${JSON.stringify(overrides[k])},` : null))
  .filter(Boolean)
  .join('\n');

const source = `// AUTO-GENERATED by scripts/apply-env.mjs from .env / .env.local — do not edit,
// do not commit (gitignored). Unset keys fall back to environment.ts defaults.
export const envOverrides: Partial<Record<${KEYS.map(k => `'${k}'`).join(' | ')}, string>> = {
${body}
};
`;

writeFileSync(outPath, source);
const applied = Object.keys(overrides);
console.log(
  applied.length
    ? `[apply-env] ${applied.map(k => `${k}=${overrides[k]}`).join(', ')}`
    : '[apply-env] no overrides, using environment.ts defaults',
);
